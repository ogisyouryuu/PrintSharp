namespace PrintSharp.Styles;

/// <summary>
/// 定义单元格边框线条样式。
/// </summary>
public enum BorderStyle
{
    /// <summary>无边框。</summary>
    None,

    /// <summary>细线。</summary>
    Thin,

    /// <summary>中等粗细线条。</summary>
    Medium,

    /// <summary>虚线。</summary>
    Dashed,

    /// <summary>点线。</summary>
    Dotted,

    /// <summary>粗线。</summary>
    Thick,

    /// <summary>双线。</summary>
    Double,

    /// <summary>极细线（发丝线）。</summary>
    Hair
}
