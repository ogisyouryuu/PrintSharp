export function resolveLabels(overrides) {
    const language = document.documentElement.lang.toLowerCase();
    const base = language.startsWith('ja') ? ja : language.startsWith('ko') ? ko
        : /^zh-(hant|tw|hk|mo)(-|$)/.test(language) ? zhTW : language.startsWith('zh') ? zhCN : en;
    return { ...base, ...overrides };
}
