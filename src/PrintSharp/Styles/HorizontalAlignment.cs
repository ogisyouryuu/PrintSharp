namespace PrintSharp.Styles;

/// <summary>
/// 单元格内容的水平对齐方式。
/// </summary>
public enum HorizontalAlignment
{
    /// <summary>常规对齐（文本靠左，数字/日期靠右）。</summary>
    General,

    /// <summary>居左对齐。</summary>
    Left,

    /// <summary>居中对齐。</summary>
    Center,

    /// <summary>居右对齐。</summary>
    Right,

    /// <summary>两端对齐。</summary>
    Justify
}
